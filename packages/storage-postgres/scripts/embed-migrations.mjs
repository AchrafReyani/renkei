// Regenerates src/migrations.ts from ../migrations so the adapter can migrate
// without touching the filesystem (Supabase Edge, bundlers, Workers). The
// output is exactly what drizzle's readMigrationFiles() would return for the
// folder — same statements, same folderMillis, same sha256 — so a database
// migrated from disk and one migrated from the embedded list agree.
// Run after `drizzle-kit generate` (wired into `pnpm db:generate`).
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const folder = `${root}migrations`;
const journal = JSON.parse(readFileSync(`${folder}/meta/_journal.json`, 'utf8'));

const entries = journal.entries.map((entry) => {
  // git checks the .sql files out with LF (see .gitattributes); normalise anyway so
  // the hash never depends on the machine that ran this script.
  const query = readFileSync(`${folder}/${entry.tag}.sql`, 'utf8').replace(/\r\n/g, '\n');
  return {
    tag: entry.tag,
    sql: query.split('--> statement-breakpoint'),
    bps: entry.breakpoints,
    folderMillis: entry.when,
    hash: createHash('sha256').update(query).digest('hex'),
  };
});

const lines = [
  '// Generated by scripts/embed-migrations.mjs from ../migrations — do not edit by hand.',
  '// `pnpm db:generate` regenerates it after drizzle-kit adds a migration.',
  "import type { MigrationMeta } from 'drizzle-orm/migrator';",
  '',
  "/** The bundled SQL migrations, in order. Equivalent to drizzle's `readMigrationFiles()` on the `migrations/` folder. */",
  'export const migrations: MigrationMeta[] = [',
  ...entries.map(
    (e) =>
      `  // ${e.tag}\n  {\n    sql: ${JSON.stringify(e.sql, null, 2).replace(/\n/g, '\n    ')},\n    bps: ${e.bps},\n    folderMillis: ${e.folderMillis},\n    hash: '${e.hash}',\n  },`,
  ),
  '];',
  '',
];
writeFileSync(`${root}src/migrations.ts`, lines.join('\n'));
// Keep the checked-in file in the repo's format so `pnpm lint` stays quiet.
execSync('pnpm exec biome format --write src/migrations.ts', { cwd: root, stdio: 'ignore' });
console.log(`embedded ${entries.length} migration(s) into src/migrations.ts`);
